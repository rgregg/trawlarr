/** The daemon side of the document store: a plain map, in THIS process. */
const recordingDocuments = () => {
  const docs = new Map<string, Record<string, unknown>>();
  const port: DocumentPort = {
    get: (collection, docId) => docs.get(`${collection}:${docId}`),
    insert: (collection, docId, data) => {
      docs.set(`${collection}:${docId}`, data);
    },
    update: (collection, docId, patch) => {
      docs.set(`${collection}:${docId}`, { ...docs.get(`${collection}:${docId}`), ...patch });
    },
    removeOne: (collection, docId) => {
      docs.delete(`${collection}:${docId}`);
    },
  };
  return { port, docs };
};

const handleFor = (documents: DocumentPort) =>
  createAgentHandle({
    id: 'w1',
    documents,
    onStep: () => {},
    onHeartbeat: () => {},
    onProgress: () => {},
    onLog: () => {},
    nowMs: () => Date.now(),
    // The seam substitutes only the PATH: this is the real production fork,
    // with its real `detached`/`stdio` options, pointed at the built agent
    // rather than at the `.js` sibling of this repo's TypeScript source.
    forkFn: () => forkAgent(AGENT_DIST),
  });

/** Whether pid is still a live process, read from the OS rather than inferred. */
const isAlive = (pid: number): boolean => {
  try {
    process.kill(pid, 0);
    return true;
  } catch {
    return false;
  }
};

const ownPgid = (): number | null => {
  try {
    const stat = readFileSync('/proc/self/stat', 'utf8');
    return Number(stat.slice(stat.lastIndexOf(')') + 2).split(' ')[2]);
  } catch {
    return null;
  }
};

describe('the forked worker agent', () => {
  beforeAll(() => {
    assertBuiltAgentIsFresh();
  });

  it('is wired to a module that exists next to its handle in the build output', () => {
    // `AGENT_MODULE_URL` resolves against THIS repo's source layout under
    // vitest, so the assertion that can be made here is the structural one:
    // production forks `agent.js` beside `agent-handle.js`, and the build
    // really does contain that pair.
    expect(basename(fileURLToPath(AGENT_MODULE_URL))).toBe(basename(AGENT_DIST));
    expect(existsSync(join(dirname(AGENT_DIST), 'agent-handle.js'))).toBe(true);
  });

  it('runs the job in a separate, detached process and round-trips the document store over IPC', async () => {
    const { port, docs } = recordingDocuments();
    const handle = handleFor(port);
    const flow = flowThrough([identityPluginPath(), readBackPluginPath()]);

    const report: JobReport = await handle.run(payloadFor(flow));

    expect(report.success).toBe(true);
    expect(report.steps.map((step) => step.nodeId)).toEqual(['start', 'n0', 'n1']);

    // Written by the plugin, in the child, THROUGH the daemon's port: the
    // document only exists here if the round trip crossed the boundary.
    const identity = docs.get('TrawlarrAgentIdentity:who') as {
      pid: number;
      ppid: number;
      pgid: number | null;
    };
    expect(identity).toBeDefined();

    // Genuinely another process — and OUR child, not something unrelated.
    expect(identity.pid).not.toBe(process.pid);
    expect(identity.ppid).toBe(process.pid);
    // ...and the pid the daemon believes it forked is the pid the child
    // itself observed, so the handle is talking to that same process.
    expect(handle.pid).toBe(identity.pid);

    // `detached: true` in one observable fact: the child leads its own
    // process group, so `kill(-pid)` reaches its whole tree and nothing
    // of ours. Without `detached` its pgid would be the daemon's.
    if (identity.pgid !== null) {
      expect(identity.pgid).toBe(identity.pid);
      expect(identity.pgid).not.toBe(ownPgid());
    }

    // The second node took output 1, which it can only do if the document
    // it read came BACK across the boundary with the value in it.
    expect(report.steps.at(-1)?.outputNumber).toBe(1);

    // And the process is gone afterwards, rather than left behind holding
    // a worker slot. Read after `exited` resolves, so no timing is involved.
    await expect(handle.exited).resolves.toBe(0);
    expect(isAlive(identity.pid)).toBe(false);
  }, 30_000);

  it('reports a child that vanishes mid-job as a vanished child, not as a failure it authored', async () => {
    const { port } = recordingDocuments();
    const handle = handleFor(port);
    const flow = flowThrough([suddenExitPluginPath()]);

    const failure = await handle.run(payloadFor(flow)).then(
      () => {
        throw new Error('expected the run to reject');
      },
      (error: unknown) => error as AgentFailure,
    );

    expect(failure).toBeInstanceOf(AgentFailure);
    // The distinction the daemon acts on: nothing authored this failure,
    // so there is no plugin error text to record — only the disappearance.
    expect(failure.reported).toBe(false);
    expect(failure.exitCode).toBe(7);
    await expect(handle.exited).resolves.toBe(7);
  }, 30_000);

  it('reports a plugin that throws as a failure the agent AUTHORED, and still exits', async () => {
    const { port } = recordingDocuments();
    const handle = handleFor(port);
    const flow = flowThrough([throwingPluginPath()]);

    // A plugin error is not an agent failure: `runPayload` folds it into a
    // report with `failed: true`, which is a completed run.
    const report = await handle.run(payloadFor(flow));
    expect(report.failed).toBe(true);
    expect(report.success).toBe(false);
    expect(report.error).toContain('plugin exploded on purpose');

    await expect(handle.exited).resolves.toBe(0);
    expect(isAlive(handle.pid ?? 0)).toBe(false);
  }, 30_000);
});
