/**
 * The one test that forks a REAL agent process.
 *
 * Everything about the protocol is proved deterministically in
 * `agent-handle.test.ts` against a fake child. What only a real fork can
 * prove is the thing a comment cannot: that the job runs in a DIFFERENT
 * process — a detached one, in its own process group — and that the
 * document store round trip really crosses that boundary. Both are read
 * out of observable state (pids the child itself reported, its process
 * group as the kernel sees it, and its absence afterwards), never from log
 * text and never from elapsed time.
 */

const AGENT_DIST = join(process.cwd(), 'packages/server/dist/worker/agent.js');
const AGENT_SRC = join(process.cwd(), 'packages/server/src/worker/agent.ts');

/**
 * This suite forks a BUILT artifact, so `pnpm test` on its own proves
 * nothing about `src/` unless `pnpm build` ran first — and `tsc --build` is
 * incremental, so a deleted or stale output is not regenerated by accident.
 * Deliberately NOT gated on `existsSync`: a missing artifact must FAIL here,
 * loudly, rather than skip and report green.
 */
const assertBuiltAgentIsFresh = (): void => {
  if (!existsSync(AGENT_DIST)) {
    throw new Error(`${AGENT_DIST} does not exist. Run "pnpm build" before this suite.`);
  }
  const builtAt = statSync(AGENT_DIST).mtimeMs;
  const sourceAt = statSync(AGENT_SRC).mtimeMs;
  if (builtAt < sourceAt) {
    throw new Error(
      `${AGENT_DIST} (built ${new Date(builtAt).toISOString()}) is older than ` +
        `${AGENT_SRC} (${new Date(sourceAt).toISOString()}) — this suite would be forking ` +
        `STALE compiled output. Run "pnpm build" (or "tsc --build --force") first.`,
    );
  }
};

const NOW = 1_700_000_000_000;

const PROBE: ProbeData = {
  streams: [
    { index: 0, codec_type: 'video', codec_name: 'hevc', width: 320, height: 240 },
    { index: 1, codec_type: 'audio', codec_name: 'aac' },
  ],
  format: { duration: '2.0', size: '4096', bit_rate: '16384' },
};

const writePlugin = (code: string): string => {
  const abs = join(mkdtempSync(join(tmpdir(), 'trawlarr-agent-plugin-')), 'index.js');
  writeFileSync(abs, code, 'utf8');
  return abs;
};

const detailsSource = (name: string, outputs: string) => `
const details = () => ({
  name: ${JSON.stringify(name)},
  description: ${JSON.stringify(name)},
  style: { borderColor: '#000000' },
  tags: 'test',
  isStartPlugin: false,
  pType: '',
  sidebarPosition: 1,
  icon: 'faQuestion',
  inputs: [],
  outputs: ${outputs},
  requiresVersion: '1.0.0',
});
`;

/**
 * Records the identity of the process it is actually running in, through
 * `crudTransDBN` — i.e. through the daemon's own document store, over IPC.
 *
 * `pgid` is read from `/proc/self/stat` (field 5, after the parenthesised
 * comm): a process whose pgid equals its own pid is a process-group LEADER,
 * which is exactly what `detached: true` buys and what lets Task 6 kill a
 * worker's whole tree, ffmpeg included, with one signal.
 */
const identityPluginPath = (): string =>
  writePlugin(`
${detailsSource('Record Identity', "[{ number: 1, tooltip: 'recorded' }]")}

const pgidOf = () => {
  try {
    const stat = require('node:fs').readFileSync('/proc/self/stat', 'utf8');
    const fields = stat.slice(stat.lastIndexOf(')') + 2).split(' ');
    return Number(fields[2]);
  } catch (error) {
    return null;
  }
};

const plugin = async (args) => {
  await args.deps.crudTransDBN('TrawlarrAgentIdentity', 'insert', 'who', {
    pid: process.pid,
    ppid: process.ppid,
    pgid: pgidOf(),
  });
  return { outputNumber: 1, outputFileObj: { _id: args.inputFileObj._id }, variables: args.variables };
};

module.exports = { details, plugin };
`);

/**
 * Reads that same document back and branches on it, so the value has to
 * cross the boundary in BOTH directions for output 1 to be taken. This is
 * the `processedCheck` shape every skip-list community plugin uses.
 */
const readBackPluginPath = (): string =>
  writePlugin(`
${detailsSource('Read Back Identity', "[{ number: 1, tooltip: 'came back' }, { number: 2, tooltip: 'did not' }]")}

const plugin = async (args) => {
  const doc = await args.deps.crudTransDBN('TrawlarrAgentIdentity', 'getById', 'who', {});
  return {
    outputNumber: doc && doc.pid === process.pid ? 1 : 2,
    outputFileObj: { _id: args.inputFileObj._id },
    variables: args.variables,
  };
};

module.exports = { details, plugin };
`);

/** A plugin that takes the process down without warning, as third-party code can. */
const suddenExitPluginPath = (): string =>
  writePlugin(`
${detailsSource('Sudden Death', "[{ number: 1, tooltip: 'never taken' }]")}

const plugin = () => {
  process.exit(7);
};

module.exports = { details, plugin };
`);

/** A plugin that throws, which the agent must REPORT rather than die of. */
const throwingPluginPath = (): string =>
  writePlugin(`
${detailsSource('Explodes', "[{ number: 1, tooltip: 'never taken' }]")}

const plugin = () => {
  throw new Error('plugin exploded on purpose');
};

module.exports = { details, plugin };
`);

const flowThrough = (pluginPaths: string[]): FlowDefinition => ({
  nodes: [
    { id: 'start', pluginId: 'trawlarr:start', pluginVersion: '1.0.0', inputs: {} },
    ...pluginPaths.map((path, index) => ({
      id: `n${String(index)}`,
      pluginId: path,
      pluginVersion: '1.0.0',
      inputs: {},
    })),
  ],
  edges: [
    { fromNodeId: 'start', outputNumber: 1, toNodeId: 'n0' },
    ...pluginPaths.slice(1).map((_, index) => ({
      fromNodeId: `n${String(index)}`,
      outputNumber: 1,
      toNodeId: `n${String(index + 1)}`,
    })),
  ],
});

